"""Milestone unit economics. Pure arithmetic over explicit, sourced assumptions.

Steady-state model per milestone (monthly):
  contribution c = ARPU*(1 - platform_fee - payment_pct) - payment_fixed - variable_cost
  to hold N customers you must replace churn: N*churn new customers, each costing CAC
  owner profit P = N*c - fixed_costs - N*churn*CAC
  => N = ceil((P + fixed) / (c - churn*CAC))
If c <= churn*CAC the model can never be profitable at that CAC, and we say so.

  python -m engine.economics research/economics.json > research/milestones.md
"""
import json
import math
import sys

MILESTONES = [
    ("M1", "First verified paying customer", None),
    ("M2", "$1,000 monthly owner profit", 1_000),
    ("M3", "$5,000 monthly owner profit", 5_000),
    ("M4", "$10,000 monthly owner profit", 10_000),
    ("M5", "$25,000 monthly owner profit", 25_000),
    ("M6", "$50,000 monthly owner profit", 50_000),
]

# What must be TRUE (measured, not assumed) before spending effort on the next milestone.
EVIDENCE_GATES = {
    "M1": "One payment settled in the payment provider (or marketplace) and recorded verified=yes in the ledger; no refund within 14 days.",
    "M2": "≥ 3 consecutive months of measured logo churn ≤ model churn; ≥ 50% of new customers from the planned organic channel; support ≤ 2 h/week.",
    "M3": "Organic channel delivers the required gross adds for 3 straight months without paid spend; measured CAC ≤ 1/3 of measured LTV; refunds < 3% of revenue.",
    "M4": "Second acquisition channel proven (≥ 20% of adds); annual-plan share ≥ 20%; automated onboarding with ≤ 10% of trials needing human help.",
    "M5": "Net revenue retention ≥ 100% (expansion offsets churn); part-time support contractor in place with documented SOPs; founder ≤ 7 h/week.",
    "M6": "12 months of verified MRR growth; customer concentration: no customer > 5% of MRR; reserve ≥ 3 months of fixed costs.",
}


def contribution(m):
    return (m["arpu_monthly"] * (1 - m["platform_fee_pct"] - m["payment_pct"])
            - m["payment_fixed"] - m["variable_cost_per_customer"])


def customers_needed(profit, m, fixed, churn):
    c = contribution(m)
    margin = c - churn * m["cac"]
    if margin <= 0:
        return None
    return math.ceil((profit + fixed) / margin)


def milestone_table(m, scenario="base"):
    churn = m["monthly_churn"][scenario]
    c = contribution(m)
    rows = []
    for mid, label, profit in MILESTONES:
        fixed = m["fixed_costs"][mid]
        if profit is None:
            rows.append({"id": mid, "label": label, "customers": 1, "mrr": m["arpu_monthly"], "fixed": fixed,
                         "gross_adds": 1, "acq_spend": m["cac"], "adds_24mo": 1, "gate": EVIDENCE_GATES[mid]})
            continue
        n = customers_needed(profit, m, fixed, churn)
        rows.append({
            "id": mid, "label": label, "customers": n,
            "mrr": None if n is None else round(n * m["arpu_monthly"]),
            "fixed": fixed,
            "gross_adds": None if n is None else math.ceil(n * churn),
            "acq_spend": None if n is None else round(math.ceil(n * churn) * m["cac"]),
            # Average new customers/mo needed to get from 0 to n in 24 months while losing `churn` of the base.
            "adds_24mo": None if n is None else math.ceil(n / 24 + n * churn / 2),
            "gate": EVIDENCE_GATES[mid],
        })
    ltv = c / churn
    return {"contribution": round(c, 2), "churn": churn, "ltv": round(ltv), "ltv_to_cac": round(ltv / m["cac"], 1) if m["cac"] else None,
            "rows": rows}


def render(models):
    out = ["# Milestone economics", "",
           "_Generated by `python -m engine.economics research/economics.json`. Every input is an assumption with a stated source or rationale (see each model). These are requirements, not forecasts: they say what must become true, and each gate says what evidence proves it._", ""]
    for m in models:
        out += [f"## {m['name']}", "", f"ARPU ${m['arpu_monthly']}/mo · platform fee {m['platform_fee_pct']*100:.0f}% · "
                f"payment {m['payment_pct']*100:.1f}% + ${m['payment_fixed']} · variable cost ${m['variable_cost_per_customer']}/customer · CAC ${m['cac']}", ""]
        out += ["Assumption sources:", ""] + [f"- {k}: {v}" for k, v in m["sources"].items()] + [""]
        for scen in ("base", "high"):
            t = milestone_table(m, scen)
            out += [f"**{scen.title()} churn {t['churn']*100:.1f}%/mo** — contribution ${t['contribution']}/customer/mo, LTV ${t['ltv']:,}, LTV:CAC {t['ltv_to_cac']}", "",
                    "| Milestone | Paying customers | MRR | Fixed costs/mo | New/mo to replace churn | Avg new/mo to reach in 24 mo | Acquisition spend/mo at steady state |",
                    "|---|---:|---:|---:|---:|---:|---:|"]
            for r in t["rows"]:
                cust = "not reachable at this CAC" if r["customers"] is None else f"{r['customers']:,}"
                mrr = "—" if r["mrr"] is None else f"${r['mrr']:,}"
                adds = "—" if r["gross_adds"] is None else r["gross_adds"]
                spend = "—" if r["acq_spend"] is None else f"${r['acq_spend']:,}"
                reach = "—" if r["adds_24mo"] is None else r["adds_24mo"]
                out.append(f"| {r['id']} {r['label']} | {cust} | {mrr} | ${r['fixed']:,} | {adds} | {reach} | {spend} |")
            out.append("")
    out += ["## Evidence required before advancing", "", "| Milestone | Gate |", "|---|---|"]
    out += [f"| {mid} {label} | {EVIDENCE_GATES[mid]} |" for mid, label, _ in MILESTONES]
    return "\n".join(out) + "\n"


def main(argv):
    models = json.load(open(argv[1]))["models"]
    sys.stdout.write(render(models))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
